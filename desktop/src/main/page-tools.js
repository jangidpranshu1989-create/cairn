// One-click page intelligence: summary, mind map, PDF export, full-page screenshot, article reading.
const { app, BrowserWindow, shell } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const dom = require('./agent/dom');
const { withPage } = require('./agent/background');
const llm = require('./llm');
const store = require('./store');

function outDir() {
  const d = store.get().settings.data.downloadDir || path.join(app.getPath('downloads'), 'Saarthi');
  fs.mkdirSync(d, { recursive: true });
  return d;
}
const slug = (s) => String(s || 'page').replace(/[^\p{L}\p{N}]+/gu, '-').replace(/^-|-$/g, '').slice(0, 60) || 'page';
const stamp = () => new Date().toISOString().replace(/[:T]/g, '-').slice(0, 16);

function langInstruction(sample) {
  const pref = store.get().settings.data.language;
  if (pref && pref !== 'auto') return `Write in ${pref === 'hinglish' ? 'Hinglish (Hindi written in Latin script, casual)' : pref}.`;
  return sample ? `Write in the same language and script the user used: "${sample.slice(0, 120)}". If the user wrote Hinglish, reply in Hinglish.` : 'Write in clear English.';
}

async function getArticle(wc) { return dom.article(wc); }
async function readUrl(url, signal) { return withPage(url, (wc) => dom.article(wc), { settleMs: 1200, scrolls: 0, signal }); }

async function summarize(wc, { userText, style = 'brief' } = {}) {
  const a = await getArticle(wc);
  if (!a.text || a.text.length < 80) throw new Error('This page has too little readable text to summarize.');
  const md = await llm.complete(
    `You are Saarthi, a browser assistant. Summarize web pages accurately. ${langInstruction(userText)} Use Markdown: a one-line TL;DR in bold, then ${style === 'detailed' ? '6-10' : '4-6'} key points as bullets, then "Key facts" (numbers, dates, names) if any. Never invent facts.`,
    `Title: ${a.title}\nURL: ${a.url}\n\n${a.text.slice(0, 24000)}`, { tier: 'smart', maxTokens: 1500 });
  return { title: a.title, url: a.url, markdown: md };
}

async function mindmap(wc, { userText } = {}) {
  const a = await getArticle(wc);
  if (!a.text || a.text.length < 80) throw new Error('Not enough content on this page to build a mind map.');
  const j = await llm.completeJSON(
    `Create a hierarchical mind map of the page. ${langInstruction(userText)} Root = page topic (max 6 words). 4-7 main branches, each with 2-5 children, optional grandchildren. Labels max 7 words. Schema: {"title":"...","children":[{"title":"...","children":[...]}]}`,
    `Title: ${a.title}\n\n${a.text.slice(0, 20000)}`, { tier: 'smart', maxTokens: 2500 });
  return { title: a.title, url: a.url, tree: j };
}

async function savePdf(wc, name) {
  const data = await wc.printToPDF({ printBackground: true, pageSize: 'A4', margins: { marginType: 'default' } });
  const file = path.join(outDir(), `${slug(name || wc.getTitle())}-${stamp()}.pdf`);
  fs.writeFileSync(file, data);
  return file;
}

/** Render arbitrary HTML (e.g. a summary or article) into a PDF */
async function htmlToPdf(html, name) {
  const win = new BrowserWindow({ show: false, webPreferences: { sandbox: true, javascript: false } });
  try {
    await win.loadURL('data:text/html;charset=utf-8,' + encodeURIComponent(html));
    const data = await win.webContents.printToPDF({ printBackground: true, pageSize: 'A4' });
    const file = path.join(outDir(), `${slug(name)}-${stamp()}.pdf`);
    fs.writeFileSync(file, data);
    return file;
  } finally { win.destroy(); }
}

const esc = (s) => String(s).replace(/[&<>]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]));
function mdToHtml(md) {
  return esc(md).split('\n').map(l => {
    if (/^##\s/.test(l)) return `<h2>${l.slice(3)}</h2>`;
    if (/^#\s/.test(l)) return `<h1>${l.slice(2)}</h1>`;
    if (/^\s*[-*]\s/.test(l)) return `<li>${l.replace(/^\s*[-*]\s/, '')}</li>`;
    return l.trim() ? `<p>${l}</p>` : '';
  }).join('\n').replace(/\*\*(.+?)\*\*/g, '<b>$1</b>').replace(/(<li>.*<\/li>\n?)+/g, m => `<ul>${m}</ul>`);
}
function documentHtml(title, url, md) {
  return `<!doctype html><html><head><meta charset="utf-8"><style>
  body{font:12pt/1.6 Georgia,'Noto Serif Devanagari',serif;color:#1b1a17;max-width:720px;margin:40px auto;padding:0 24px}
  h1{font:700 22pt/1.2 system-ui,sans-serif;margin:0 0 6px} h2{font:700 14pt system-ui,sans-serif;margin:22px 0 6px}
  .src{color:#777;font:9pt system-ui,sans-serif;margin-bottom:24px;word-break:break-all} li{margin:4px 0}
  .ft{margin-top:40px;color:#999;font:8pt system-ui,sans-serif;border-top:1px solid #ddd;padding-top:8px}
  </style></head><body><h1>${esc(title)}</h1><div class="src">${esc(url)}</div>${mdToHtml(md)}<div class="ft">Generated by Saarthi Browser · ${new Date().toLocaleString()}</div></body></html>`;
}

/** Full-page ("long") screenshot using the DevTools protocol */
async function longScreenshot(wc, name) {
  const dbg = wc.debugger;
  const attached = dbg.isAttached();
  if (!attached) dbg.attach('1.3');
  try {
    const m = await dbg.sendCommand('Page.getLayoutMetrics');
    const size = m.cssContentSize || m.contentSize;
    const vw = m.cssLayoutViewport?.clientWidth || m.layoutViewport.clientWidth;
    const width = Math.ceil(vw), height = Math.min(Math.ceil(size.height), 30000);
    const scale = height > 16000 ? 16000 / height : 1; // keep within GPU texture limits
    // Resize the virtual viewport to the full page, capture once, then restore.
    await dbg.sendCommand('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: scale, mobile: false });
    await new Promise(r => setTimeout(r, 600));
    let shot;
    try { shot = await dbg.sendCommand('Page.captureScreenshot', { format: 'png', fromSurface: true, captureBeyondViewport: false }); }
    finally { await dbg.sendCommand('Emulation.clearDeviceMetricsOverride').catch(() => {}); }
    const file = path.join(outDir(), `${slug(name || wc.getTitle())}-full-${stamp()}.png`);
    fs.writeFileSync(file, Buffer.from(shot.data, 'base64'));
    return { file, width: Math.round(width * scale), height: Math.round(height * scale) };
  } finally { if (!attached) try { dbg.detach(); } catch {} }
}

async function visibleScreenshot(wc) {
  const img = await wc.capturePage();
  const file = path.join(outDir(), `${slug(wc.getTitle())}-${stamp()}.png`);
  fs.writeFileSync(file, img.toPNG());
  return file;
}

async function downloadUrl(session, url, filename) {
  const r = await session.fetch(url);
  if (!r.ok) throw new Error(`Download failed (${r.status})`);
  const buf = Buffer.from(await r.arrayBuffer());
  let name = filename || decodeURIComponent(new URL(url).pathname.split('/').pop() || 'download');
  const file = path.join(outDir(), name.replace(/[\\/:*?"<>|]/g, '_'));
  fs.writeFileSync(file, buf);
  return file;
}

module.exports = { summarize, mindmap, savePdf, htmlToPdf, documentHtml, longScreenshot, visibleScreenshot, getArticle, readUrl, downloadUrl, outDir, langInstruction,
  reveal: (f) => shell.showItemInFolder(f), open: (f) => shell.openPath(f) };
