// Generates android/app/src/main/assets/agent.js from the desktop agent's page scripts,
// so both platforms share exactly the same DOM logic. Run: node tools/gen_android_agent_js.js
const fs = require('fs'), path = require('path');
const read = (p) => fs.readFileSync(path.join(__dirname, '..', p), 'utf8');
const src = read('desktop/src/main/agent/dom.js') + '\n' + read('desktop/src/main/agent/shopping.js');
const grab = (name) => { const i = src.indexOf(`function ${name}(`); if (i < 0) throw new Error(name);
  let d = 0, j = src.indexOf('{', i); for (; j < src.length; j++) { if (src[j] === '{') d++; else if (src[j] === '}' && --d === 0) break; } return src.slice(i, j + 1); };
const fns = ['snapshotFn', 'locateFn', 'findByTextFn', 'focusFn', 'selectFn', 'scrollFn', 'articleFn', 'overlayFn', 'pageStateFn', 'extractListingsFn'];
const extra = `
function typeFn(id, text, submit) {
  const el = document.querySelector('[data-saarthi-id="' + id + '"]');
  if (!el) return false;
  el.scrollIntoView({ block: 'center', behavior: 'instant' }); el.focus();
  if (el.isContentEditable) { document.execCommand('selectAll'); document.execCommand('insertText', false, text); }
  else {
    const proto = el.tagName === 'TEXTAREA' ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype;
    Object.getOwnPropertyDescriptor(proto, 'value').set.call(el, text);
    el.dispatchEvent(new InputEvent('input', { bubbles: true, data: text, inputType: 'insertText' }));
    el.dispatchEvent(new Event('change', { bubbles: true }));
  }
  if (submit) {
    const o = { key: 'Enter', code: 'Enter', keyCode: 13, which: 13, bubbles: true };
    el.dispatchEvent(new KeyboardEvent('keydown', o)); el.dispatchEvent(new KeyboardEvent('keypress', o)); el.dispatchEvent(new KeyboardEvent('keyup', o));
    if (el.form) { if (el.form.requestSubmit) el.form.requestSubmit(); else el.form.submit(); }
  }
  return true;
}
function keyFn(key) {
  const el = document.activeElement || document.body;
  const codes = { Enter: 13, Escape: 27, Tab: 9, ArrowDown: 40, ArrowUp: 38, Backspace: 8 };
  const o = { key, code: key, keyCode: codes[key] || 0, which: codes[key] || 0, bubbles: true };
  el.dispatchEvent(new KeyboardEvent('keydown', o)); el.dispatchEvent(new KeyboardEvent('keyup', o));
  if (key === 'Enter' && el.form) { if (el.form.requestSubmit) el.form.requestSubmit(); else el.form.submit(); }
  return true;
}
function countLinksFn(src) { const re = new RegExp(src); return [...document.querySelectorAll('a[href]')].filter(a => re.test(a.href)).length; }
function blockedFn() { return /503|robot|captcha|access denied|unusual traffic/i.test(document.title + ' ' + (document.body ? document.body.innerText.slice(0, 400) : '')); }
function metricsFn() { return { w: innerWidth, h: innerHeight, dpr: devicePixelRatio, sh: document.documentElement.scrollHeight, y: scrollY }; }
function hideFixedFn(hide) {
  if (hide) { document.querySelectorAll('body *').forEach(e => { const p = getComputedStyle(e).position; if ((p === 'fixed' || p === 'sticky') && e.id !== '__saarthi_overlay') { e.dataset.saarthiHid = e.style.visibility || '-'; e.style.visibility = 'hidden'; } }); }
  else document.querySelectorAll('[data-saarthi-hid]').forEach(e => { e.style.visibility = e.dataset.saarthiHid === '-' ? '' : e.dataset.saarthiHid; delete e.dataset.saarthiHid; });
  return true;
}`;
// On Android the glowing edge is drawn natively around the web view, so the in-page overlay only shows the cursor.
const body = fns.map(grab).join('\n').replace('<div class="glow"></div>', '');
const out = `/* Generated by tools/gen_android_agent_js.js — do not edit by hand. */
(function () {
  if (window.__saarthi) return;
${body}
${extra}
  const api = { snapshot: snapshotFn, locate: locateFn, findByText: findByTextFn, focus: focusFn, select: selectFn, scroll: scrollFn,
    article: articleFn, overlay: overlayFn, pageState: pageStateFn, listings: extractListingsFn, type: typeFn, key: keyFn,
    countLinks: countLinksFn, blocked: blockedFn, metrics: metricsFn, hideFixed: hideFixedFn };
  Object.defineProperty(window, '__saarthi', { value: Object.freeze(api), writable: false, configurable: false });
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'android/app/src/main/assets/agent.js'), out);
console.log('ok', out.length);
