// Generates android/app/src/main/assets/agent.js from the desktop agent's page scripts,
// so both platforms share exactly the same DOM logic. Run: node tools/gen_android_agent_js.js
const fs = require('fs'), path = require('path');
const read = (p) => fs.readFileSync(path.join(__dirname, '..', p), 'utf8');
const src = read('desktop/src/main/agent/dom.js') + '\n' + read('desktop/src/main/agent/shopping.js');
const grab = (name) => { const i = src.indexOf(`function ${name}(`); if (i < 0) throw new Error(name);
  let d = 0, j = src.indexOf('{', i); for (; j < src.length; j++) { if (src[j] === '{') d++; else if (src[j] === '}' && --d === 0) break; } return src.slice(i, j + 1); };
const fns = ['snapshotFn', 'locateFn', 'findByTextFn', 'focusFn', 'selectFn', 'scrollFn', 'articleFn', 'overlayFn', 'pageStateFn', 'extractListingsFn'];
const extra = read('tools/android_page_extra.js');
// On Android the glowing edge is drawn natively around the web view, so the in-page overlay only shows the cursor.
const body = fns.map(grab).join('\n').replace('<div class="glow"></div>', '');
const out = `/* Generated by tools/gen_android_agent_js.js — do not edit by hand. */
(function () {
  if (window.__cairn) return;
${body}
${extra}
  const api = { snapshot: snapshotFn, locate: locateFn, findByText: findByTextFn, focus: focusFn, select: selectFn, scroll: scrollFn,
    article: articleFn, overlay: overlayFn, pageState: pageStateFn, listings: extractListingsFn, type: typeFn, key: keyFn,
    countLinks: countLinksFn, blocked: blockedFn, metrics: metricsFn, hideFixed: hideFixedFn,
    clickEl: clickElFn, fillProfile: fillProfileFn, offers: offersFn, applyCoupon: applyCouponFn, guard: guardFn, region: regionFn,
    product: productFn, textNodes: textNodesFn, setTexts: setTextsFn, icons: iconsFn };
  Object.defineProperty(window, '__cairn', { value: Object.freeze(api), writable: false, configurable: false });
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'android/app/src/main/assets/agent.js'), out);
console.log('ok', out.length);
